-- 1. LEADS TABLE
create table if not exists public.leads (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  business_name text not null,
  contact_name text default '',
  phone text default '',
  email text default '',
  website_url text default '',
  google_maps_url text default '',
  category_name text default 'Jewellery Stores',
  country text default 'India',
  state text default '',
  district text default '',
  city text default '',
  locality text default '',
  location_id integer,
  address text default '',
  website_status text default 'No Website',
  source text default 'Manual Entry',
  status text default 'New Lead',
  priority text default 'Medium',
  assigned_outreacher_id bigint,
  assigned_developer_id bigint,
  estimated_deal_value numeric default 0,
  agreed_deal_value numeric default 0,
  next_follow_up_at text default '',
  last_contacted_at text default '',
  notes text default '',
  tags text default '',
  is_archived boolean default false,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

alter table public.leads enable row level security;

create policy "Users can view their own leads"
  on public.leads for select
  using (auth.uid() = user_id);

create policy "Users can insert their own leads"
  on public.leads for insert
  with check (auth.uid() = user_id);

create policy "Users can update their own leads"
  on public.leads for update
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

create policy "Users can delete their own leads"
  on public.leads for delete
  using (auth.uid() = user_id);


